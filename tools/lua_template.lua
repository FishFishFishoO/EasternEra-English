function Mod:ApplyTable(DT, T, Stats)
    local Struct = UE[T.struct]
    if not Struct then
        Stats.Failed = Stats.Failed + 1
        self:Note("no struct " .. T.struct .. " for " .. T.name)
        return
    end
    for RowName, Sets in pairs(T.rows) do
        local ok, err = pcall(function()
            local Row = Struct()
            assert(UE.UDataTableFunctionLibrary.GetDataTableRowFromName(DT, Name(RowName), Row), "row not found")
            local Done = 0
            for _, S in ipairs(Sets) do
                local okSet, errSet = pcall(SetAt, Row, S[1], 1, Text(S[2]))
                if okSet then Done = Done + 1 else
                    Stats.Failed = Stats.Failed + 1
                    self:Note(T.name .. "/" .. RowName .. ": " .. tostring(errSet))
                end
            end
            if Done > 0 then
                assert(UE.UModLuaLibrary.ReplaceDataTableRow(DT, Name(RowName), Row), "write failed")
                Stats.Fields = Stats.Fields + Done
            end
        end)
        if not ok then
            Stats.Failed = Stats.Failed + #Sets
            self:Note(T.name .. "/" .. RowName .. ": " .. tostring(err))
        end
    end
end

function Mod:ApplyTables(UseConfig, Stats)
    local Config = UseConfig and self:ConfigTables() or nil
    if UseConfig and not Config then return false end
    for _, T in ipairs(TABLES) do
        local DT
        if UseConfig then
            for N, Obj in pairs(Config) do
                if N == T.name or string.sub(N, 1, #T.name + 1) == T.name .. "_" then DT = Obj break end
            end
        else
            local ok, Obj = pcall(function() return UE.UObject.Load(T.path) end)
            DT = ok and Obj or nil
            if DT then pcall(function() UnLua.Ref(DT) end) end
        end
        if DT then self:ApplyTable(DT, T, Stats) elseif not UseConfig then
            Stats.Failed = Stats.Failed + 1
            self:Note("table not found: " .. T.path)
        end
    end
    return true
end

function Mod:ApplyObjects(Stats)
    for _, O in ipairs(OBJECTS) do
        local ok, err = pcall(function()
            local Obj = UE.UObject.Load(O.path)
            assert(Obj, "not found")
            pcall(function() UnLua.Ref(Obj) end)  -- keep the edited template loaded
            for _, S in ipairs(O.sets) do
                local okSet, errSet = pcall(SetAt, Obj, S[1], 1, Text(S[2]))
                if okSet then Stats.Fields = Stats.Fields + 1 else
                    Stats.Failed = Stats.Failed + 1
                    self:Note(O.path .. ": " .. tostring(errSet))
                end
            end
        end)
        if not ok then
            Stats.Failed = Stats.Failed + #O.sets
            self:Note(O.path .. ": " .. tostring(err))
        end
    end
end

-- Slot size: read the struct, change it, hand it back through the setter.
local function SetSlotSize(Slot, Rule)
    local Size = Slot.Size
    Size.SizeRule = Rule
    Size.Value = 1.0
    Slot:SetSize(Size)
end

function Mod:ApplyLayout(Stats)
    for _, L in ipairs(LAYOUT) do
        local ok, err = pcall(function()
            local W = UE.UObject.Load(L.widget)
            assert(W, "not found")
            pcall(function() UnLua.Ref(W) end)  -- keep the edited template loaded
            if L.slot_size then
                assert(W.Slot, "no slot")
                SetSlotSize(W.Slot, L.slot_size)
            end
            if L.overflow then W:SetTextOverflowPolicy(L.overflow) end
            if L.clip then W:SetClipping(L.clip) end
            if L.visibility then
                if not pcall(function() W:SetVisibility(L.visibility) end) then W.Visibility = L.visibility end
            end
            if L.scale then
                local S = UE.FVector2D(L.scale, L.scale)
                local P = UE.FVector2D(L.pivot[1], L.pivot[2])
                if not pcall(function() W:SetRenderScale(S) W:SetRenderTransformPivot(P) end) then
                    local RT = W.RenderTransform
                    RT.Scale = S
                    W.RenderTransform = RT
                    W.RenderTransformPivot = P
                end
            end
        end)
        if ok then Stats.Layout = Stats.Layout + 1 else
            Stats.Failed = Stats.Failed + 1
            self:Note(L.widget .. ": " .. tostring(err))
        end
    end
end

function Mod:ApplyWrap(Stats)
    if not WRAP_TEXT then return end
    for _, Path in ipairs(WRAP) do
        local ok, err = pcall(function()
            local W = UE.UObject.Load(Path)
            assert(W, "not found")
            pcall(function() UnLua.Ref(W) end)  -- keep the edited template loaded
            SetWrap(W)
        end)
        if ok then Stats.Wrap = Stats.Wrap + 1 else
            Stats.Failed = Stats.Failed + 1
            self:Note(Path .. " (wrap): " .. tostring(err))
        end
    end
end

function Mod:Apply(Where, UseConfig)
    if not IsEnglish() then
        self:Log("game language is not English; built-in text left alone")
        return true
    end
    local Stats = { Fields = 0, Layout = 0, Wrap = 0, Failed = 0 }
    local ok, result = pcall(function()
        self:ApplyTables(false, Stats)
        self:ApplyObjects(Stats)
        self:ApplyLayout(Stats)
        self:ApplyWrap(Stats)
        if UseConfig then return self:ApplyTables(true, Stats) end
        return true
    end)
    self:Log(string.format("[%s] %d fields in English, %d layout fixes, %d text boxes wrap, %d failed%s", Where, Stats.Fields,
        Stats.Layout, Stats.Wrap, Stats.Failed,
        ok and "" or (" (" .. tostring(result) .. ")")))
    return ok and result
end

function Mod:StartRetryTimer(Where)
    self:StopRetryTimer()
    local Tries = 0
    self._TimerId = UE.UModLuaLibrary.RegisterModRepeatingTimer(nil, RETRY_INTERVAL, true, function()
        Tries = Tries + 1
        if self:Apply(Where .. "/retry", true) or Tries >= MAX_RETRIES then
            self:StopRetryTimer()
        end
    end)
end

function Mod:StopRetryTimer()
    if self._TimerId then
        pcall(function() UE.UModLuaLibrary.UnregisterModRepeatingTimer(self._TimerId) end)
        self._TimerId = nil
    end
end

function Mod:OnModLoaded()
    self:Log("Xianxia English (built-in text) loaded")
    self:Apply("load", false)
    self._EventIds = {}
    for _, EventName in ipairs({ "OnNewGameStarted", "OnLoadGameComplete" }) do
        pcall(function()
            local Id = UE.UModEventBus.RegisterModEvent(EventName, function()
                if not self:Apply(EventName, true) then self:StartRetryTimer(EventName) end
            end)
            table.insert(self._EventIds, Id)
        end)
    end
end

function Mod:OnModUnloaded()
    self:StopRetryTimer()
    for _, Id in ipairs(self._EventIds or {}) do
        pcall(function() UE.UModEventBus.UnregisterModEvent(Id) end)
    end
end

return Mod
