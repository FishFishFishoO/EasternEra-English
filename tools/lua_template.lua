function Mod:Log(Message)
    -- Only "error" level reliably reaches the game log.
    UE.UModLuaLibrary.ModLog(self.ModInfo.Metadata.ModId, Message, "error")
end

function Mod:Note(Message)
    self._Notes = self._Notes or 0
    if self._Notes < MAX_NOTES then self:Log(Message) end
    self._Notes = self._Notes + 1
end

local function Text(s) return UE.UKismetTextLibrary.Conv_StringToText(s) end

-- Word wrap on one text widget template. TextBlock and CommonTextBlock have the setter; fall back to
-- the property for widget classes that don't.
local function SetWrap(W)
    local ok = pcall(function() W:SetAutoWrapText(true) end)
    if not ok then W.AutoWrapText = true end
end
local function Name(s) return UE.UKismetStringLibrary.Conv_StringToName(s) end

local function IsEnglish()
    if not ONLY_IN_ENGLISH then return true end
    local ok, Culture = pcall(function() return UE.UKismetInternationalizationLibrary.GetCurrentCulture() end)
    if not ok or not Culture then return true end
    return string.lower(string.sub(tostring(Culture), 1, 2)) == "en"
end

-- A step is "Field", a 0-based array index, or {k = map key}. UnLua arrays count from 1.
local function GetStep(C, S)
    if type(S) == "string" then return C[S] end
    if type(S) == "number" then return C:Get(S + 1) end
    return C:Find(S.k)
end

local function PutStep(C, S, V)
    if type(S) == "string" then C[S] = V
    elseif type(S) == "number" then C:Set(S + 1, V)
    else C:Add(S.k, V) end
end

-- Walk down, set the text, and write every copied struct back on the way up. Arrays and maps
-- read off a struct are live references, so they are not written back themselves.
local function SetAt(C, Steps, N, V)
    local S = Steps[N]
    if N == #Steps then PutStep(C, S, V) return end
    local Child = GetStep(C, S)
    assert(Child ~= nil, "missing " .. tostring(type(S) == "table" and S.k or S))
    SetAt(Child, Steps, N + 1, V)
    if type(Steps[N + 1]) == "string" then PutStep(C, S, Child) end
end

function Mod:GetWorld()
    local GI = UE.UGameplayStatics.GetGameInstance(self.ModInfo)
    if not GI then return nil end
    return GI:GetWorld()
end

-- The tables the running game hands out, by name. They can be other objects than the ones loaded
-- by path (the Traits mod saw this), so both get the text.
function Mod:ConfigTables()
    local World = self:GetWorld()
    if not World then return nil end
    local GM = UE.UGameplayStatics.GetGameMode(World)
    if not GM or not GM.GameConfigComponent then return nil end
    local ByName = {}
    for _, TypeName in ipairs(CONFIG_TYPES) do
        pcall(function()
            local DT = GM.GameConfigComponent:GetGameConfigByType(UE.EGameConfigType[TypeName])
            if DT and DT:IsValid() then
                ByName[UE.UKismetSystemLibrary.GetObjectName(DT)] = DT
            end
        end)
    end
    return ByName
end

